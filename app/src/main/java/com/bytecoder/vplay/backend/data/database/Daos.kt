@Dao
interface FileMetadataDao {
    @Query("SELECT * FROM file_metadata WHERE path = :path")
    suspend fun getMetadata(path: String): FileMetadata?

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertMetadata(metadata: FileMetadata)

    @Query("SELECT * FROM file_metadata WHERE mimeType LIKE 'video/%' ORDER BY lastModified DESC")
    fun getAllVideoMetadata(): LiveData<List<FileMetadata>>

    @Query("SELECT * FROM file_metadata WHERE mimeType LIKE 'audio/%' ORDER BY lastModified DESC")
    fun getAllAudioMetadata(): LiveData<List<FileMetadata>>

    @Query("SELECT DISTINCT artist FROM file_metadata WHERE artist IS NOT NULL AND artist != '' ORDER BY artist ASC")
    fun getAllArtists(): LiveData<List<String>>

    @Query("SELECT DISTINCT album FROM file_metadata WHERE album IS NOT NULL AND album != '' ORDER BY album ASC")
    fun getAllAlbums(): LiveData<List<String>>

    @Query("SELECT DISTINCT genre FROM file_metadata WHERE genre IS NOT NULL AND genre != '' ORDER BY genre ASC")
    fun getAllGenres(): LiveData<List<String>>

    @Query("SELECT * FROM file_metadata WHERE artist = :artist ORDER BY album ASC, track ASC")
    fun getFilesByArtist(artist: String): LiveData<List<FileMetadata>>

    @Query("SELECT * FROM file_metadata WHERE album = :album ORDER BY track ASC")
    fun getFilesByAlbum(album: String): LiveData<List<FileMetadata>>

    @Query("SELECT * FROM file_metadata WHERE genre = :genre ORDER BY artist ASC, album ASC")
    fun getFilesByGenre(genre: String): LiveData<List<FileMetadata>>

    @Query("DELETE FROM file_metadata WHERE analyzedAt < :before")
    suspend fun deleteOldMetadata(before: Long)
}


